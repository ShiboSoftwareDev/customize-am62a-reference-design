function createNumberedSchematicPaths(params: { count: number; directory: string }): string[] {
  return Array.from(
    { length: params.count },
    (_, sheetIndex) => `${params.directory}/${String(sheetIndex + 1).padStart(2, "0")}.SchDoc`,
  )
}

